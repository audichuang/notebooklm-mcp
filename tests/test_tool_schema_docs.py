"""每個 MCP 參數都要有 schema 描述,而且描述表不能長出孤兒。

紅了要做的:新參數就補一句它**實際**的語意(`_param_docs.py`);孤兒就刪掉那一筆。
"""

from notebooklm_mcp import _param_docs, app


async def _tools():
    return await app.mcp.list_tools()


async def test_every_parameter_has_a_description():
    missing = [
        f"{t.name}.{name}"
        for t in await _tools()
        for name, prop in t.inputSchema["properties"].items()
        if not prop.get("description", "").strip()
    ]
    assert not missing, f"這些參數沒有描述:{missing}"


async def test_description_table_has_no_orphans():
    tools = {t.name: set(t.inputSchema["properties"]) for t in await _tools()}
    params = set().union(*tools.values())
    assert not set(_param_docs.COMMON) - params
    stale = [k for k in _param_docs.BY_TOOL if k[1] not in tools.get(k[0], ())]
    assert not stale, f"這些描述對不到參數:{stale}"


async def test_autogenerated_titles_are_stripped():
    """pydantic 自動產生的 title 是參數名換皮,卻佔 5 千多字元的固定成本。"""
    for t in await _tools():
        assert "title" not in t.inputSchema
        assert not [k for k, v in t.inputSchema["properties"].items() if "title" in v]
