"""每個 MCP 參數都要有 schema 描述,而且描述表不能長出孤兒。

紅了要做的:新參數就補一句它**實際**的語意(`_param_docs.py`);孤兒就刪掉那一筆。
"""

from notebooklm_mcp import _param_docs, app


async def _tools():
    return await app.mcp.list_tools()


async def test_every_parameter_has_a_description():
    missing = [
        f"{t.name}.{name}"
        for t in await _tools()
        for name, prop in t.inputSchema["properties"].items()
        if not prop.get("description", "").strip()
    ]
    assert not missing, f"這些參數沒有描述:{missing}"


async def test_description_table_has_no_orphans():
    tools = {t.name: set(t.inputSchema["properties"]) for t in await _tools()}
    params = set().union(*tools.values())
    assert not set(_param_docs.COMMON) - params
    stale = [k for k in _param_docs.BY_TOOL if k[1] not in tools.get(k[0], ())]
    assert not stale, f"這些描述對不到參數:{stale}"


async def test_autogenerated_titles_are_stripped():
    """pydantic 自動產生的 title 是參數名換皮,卻佔 5 千多字元的固定成本。"""
    for t in await _tools():
        assert "title" not in t.inputSchema
        assert not [k for k, v in t.inputSchema["properties"].items() if "title" in v]


async def test_descriptions_carry_no_docstring_indentation():
    """docstring 續行的 4 格縮排原樣進 tools/list,每行都是白付的 token(Python 3.13 前不會自動去)。"""
    import inspect

    indented = [t.name for t in await _tools() if t.description != inspect.cleandoc(t.description)]
    assert not indented, f"這些工具描述還帶縮排:{indented}"


async def test_tool_results_are_compact_json(fake_client):
    """FastMCP 預設用 indent=2 序列化 dict 回傳;實測 30 筆 artifact_list 多 14% token。

    走真正的 `call_tool` 路徑:直接呼叫模組函式看不到序列化,SDK 改行為時也只有這條會紅。
    """
    import json

    result = await app.mcp.call_tool("notebook_list", {})
    content = result[0] if isinstance(result, tuple) else result
    text = content[0].text
    assert "\n" not in text and ": " not in text, text
    assert json.loads(text) == {"notebooks": [{"notebook_id": "nb-123", "title": "Test"}]}


async def test_compact_result_passes_non_dicts_through():
    """字串與 list 交回 FastMCP 照舊處理(list 會被拆成多個 content block)。"""

    async def returns(value):
        return value

    wrapped = _param_docs._compact_result(returns)
    assert await wrapped("已是字串") == "已是字串"
    assert await wrapped([{"a": 1}]) == [{"a": 1}]
    assert await wrapped({"中文": [1, None]}) == '{"中文":[1,null]}'
